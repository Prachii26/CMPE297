"""The search-and-control module -- the code AIDE2's outer loop rewrites.

The inner agent's engine (aide_inner.py) is fixed. Everything that decides
HOW it searches lives in a separate, generated Python module with four
slots, and that module's source text is what the outer loop edits:

  BRANCHING                 children tried per expansion
  select_node(frontier,rng) node selection rule
  order_strategies(...)     repair-strategy ordering
  should_stop(stats)        stopping condition (PATIENCE is its constant)

Each slot has a library of implementations. A ControlSpec picks one per
slot; render() writes the module; load() compiles it under the filename
"<control:...>", which task.boundary recognises on the call stack. The guard
scans the rendered source before it is ever loaded.

The inner budget (INNER_BUDGET attempts) is NOT in this module: it belongs
to the outer loop, so every variant is benchmarked at the same cost.
"""
from __future__ import annotations

import hashlib
import math
import textwrap
import types
from dataclasses import dataclass, field, replace

SELECT_NODE = {
    "greedy": """
return max(frontier, key=lambda n: (n.score, -n.depth))
""",
    "depth_penalty": """
return max(frontier, key=lambda n: n.score - 0.02 * n.depth)
""",
    "ucb": """
total = sum(n.visits for n in frontier) + 1
return max(frontier, key=lambda n: n.score + 0.15 * math.sqrt(math.log(total + 1) / (n.visits + 1)))
""",
    "breadth_first": """
return min(frontier, key=lambda n: (n.depth, n.uid))
""",
    "random": """
return frontier[int(rng.integers(len(frontier)))]
""",
}

ORDER_STRATEGIES = {
    # the proposer's own prior: coverage-append handlers first (weight 3)
    "prior_weight": """
return sorted(cands, key=lambda c: -c.weight)
""",
    "failures_first": """
return sorted(cands, key=lambda c: (-c.fails, -c.weight))
""",
    "mechanism_first": """
return sorted(cands, key=lambda c: (not c.is_mechanism, -c.fails, -c.weight))
""",
    "front_first": """
return sorted(cands, key=lambda c: (not c.is_prepend, -c.fails, -c.weight))
""",
    "novel_first": """
return sorted(cands, key=lambda c: (history.tried(c.sid) > 0, -c.fails, -c.weight))
""",
    # learn within the run: what has improved steering so far goes first
    "learned": """
return sorted(cands, key=lambda c: (-(history.gains(c.sid) + 1) / (history.tried(c.sid) + 2),
                                    -c.fails, -c.weight))
""",
}

SHOULD_STOP = {
    "budget_or_patience": """
return stats.since_improvement >= PATIENCE
""",
    "budget_only": """
return False
""",
}

BRANCHING_VALUES = (1, 2, 3, 4, 6)
PATIENCE_VALUES = (4, 6, 10, 16)

SLOTS = ("select_node", "order_strategies", "should_stop", "BRANCHING", "PATIENCE")


@dataclass(frozen=True)
class ControlSpec:
    select_node: str = "greedy"
    order_strategies: str = "prior_weight"
    should_stop: str = "budget_or_patience"
    BRANCHING: int = 2
    PATIENCE: int = 6
    # lineage: which outer generation set each slot's current value
    origin: tuple[tuple[str, int], ...] = field(
        default_factory=lambda: tuple((s, 0) for s in SLOTS))

    def value(self, slot: str):
        return getattr(self, slot)

    def with_slot(self, slot: str, value, generation: int) -> "ControlSpec":
        origin = dict(self.origin)
        origin[slot] = generation
        return replace(self, **{slot: value}, origin=tuple(origin.items()))

    def choices(self) -> dict:
        return {s: self.value(s) for s in SLOTS}

    def render(self) -> str:
        def fn(name, args, body):
            return f"def {name}({args}):\n" + textwrap.indent(textwrap.dedent(body).strip(),
                                                              "    ") + "\n"
        return "\n".join([
            '"""Search-and-control module for the AIDE2 inner agent.',
            "",
            "GENERATED by 03_aide2/aide_control.py from:",
            *[f"  {s} = {self.value(s)!r}" for s in SLOTS],
            '"""',
            "import math",
            "",
            f"BRANCHING = {self.BRANCHING}",
            f"PATIENCE = {self.PATIENCE}",
            "",
            "",
            fn("select_node", "frontier, rng", SELECT_NODE[self.select_node]),
            "",
            fn("order_strategies", "cands, node, history, rng",
               ORDER_STRATEGIES[self.order_strategies]),
            "",
            fn("should_stop", "stats", SHOULD_STOP[self.should_stop]),
        ])

    def key(self) -> str:
        return hashlib.sha256(self.render().encode()).hexdigest()[:12]


def load(source: str, tag: str = "variant") -> types.SimpleNamespace:
    code = compile(source, f"<control:{tag}>", "exec")
    ns: dict = {"__name__": "aide_control_module", "math": math}
    exec(code, ns)
    return types.SimpleNamespace(BRANCHING=ns["BRANCHING"], PATIENCE=ns["PATIENCE"],
                                 select_node=ns["select_node"],
                                 order_strategies=ns["order_strategies"],
                                 should_stop=ns["should_stop"], source=source)


def library_size() -> dict:
    return {"select_node": len(SELECT_NODE), "order_strategies": len(ORDER_STRATEGIES),
            "should_stop": len(SHOULD_STOP), "BRANCHING": len(BRANCHING_VALUES),
            "PATIENCE": len(PATIENCE_VALUES)}


def options(slot: str) -> tuple:
    return {"select_node": tuple(SELECT_NODE), "order_strategies": tuple(ORDER_STRATEGIES),
            "should_stop": tuple(SHOULD_STOP), "BRANCHING": BRANCHING_VALUES,
            "PATIENCE": PATIENCE_VALUES}[slot]


assert math  # used by generated code
